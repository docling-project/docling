"""Reading-order regression fixtures captured from PDF conversions."""

from typing import Literal, cast

from docling_core.types.doc.base import CoordOrigin, Size
from docling_core.types.doc.labels import DocItemLabel

from docling.models.postprocessing.reading_order_rb import (
    PageElement,
    ReadingOrderPredictor,
    SeparatorElement,
)


def _predict_cids(element_rows: str, separator_rows: str, page_size: Size) -> list[int]:
    page_elements = []
    for row in element_rows.strip().splitlines():
        cid, page_no, label, left, bottom, right, top = row.split()
        page_elements.append(
            PageElement(
                cid=int(cid),
                page_no=int(page_no),
                page_size=page_size,
                label=DocItemLabel(label),
                l=float(left),
                b=float(bottom),
                r=float(right),
                t=float(top),
                coord_origin=CoordOrigin.BOTTOMLEFT,
            )
        )

    page_separators = []
    for row in separator_rows.strip().splitlines():
        cid, page_no, orientation, left, bottom, right, top = row.split()
        page_separators.append(
            SeparatorElement(
                cid=int(cid),
                page_no=int(page_no),
                page_size=page_size,
                orientation=cast(Literal["horizontal", "vertical"], orientation),
                l=float(left),
                b=float(bottom),
                r=float(right),
                t=float(top),
                coord_origin=CoordOrigin.BOTTOMLEFT,
            )
        )

    return [
        element.cid
        for element in ReadingOrderPredictor().predict_reading_order(
            page_elements=page_elements, page_separators=page_separators
        )
    ]


def _assert_complete_page_order(
    element_rows: str, order: list[int], expected_rows: str
) -> None:
    expected_by_page: dict[int, list[int]] = {}
    for row in expected_rows.strip().splitlines():
        page_no, *cids = (int(value) for value in row.split())
        expected_by_page[page_no] = cids

    input_by_page: dict[int, list[int]] = {}
    for row in element_rows.strip().splitlines():
        cid, page_no = (int(value) for value in row.split()[:2])
        input_by_page.setdefault(page_no, []).append(cid)

    assert {page: sorted(cids) for page, cids in expected_by_page.items()} == {
        page: sorted(cids) for page, cids in input_by_page.items()
    }
    assert order == [
        cid for page_no in sorted(expected_by_page) for cid in expected_by_page[page_no]
    ]


