"""Visible-rule separators on real PDF pages, without ML models.

Layout clusters and separators captured from converting page 1 of
tests/data/pdf/sources/newspaper-00.pdf and elsevier-00.pdf, the pages where
the separators change the order. The e2e ground truth covers the full order;
here only the separator contract is checked: a horizontal rule is a
synchronisation point, so within its span everything above it is read before
anything below it.
"""

from typing import Literal, cast

from docling_core.types.doc.base import CoordOrigin, Size
from docling_core.types.doc.labels import DocItemLabel

from docling.models.postprocessing.reading_order_rb import (
    PageElement,
    ReadingOrderPredictor,
    SeparatorElement,
)


def _assert_rules_divide_bands(
    element_rows: str, separator_rows: str, page_size: Size
) -> None:
    elements = [
        PageElement(
            cid=int(cid),
            page_no=1,
            page_size=page_size,
            label=DocItemLabel(label),
            l=float(left),
            b=float(bottom),
            r=float(right),
            t=float(top),
            coord_origin=CoordOrigin.BOTTOMLEFT,
        )
        for cid, label, left, bottom, right, top in (
            row.split() for row in element_rows.strip().splitlines()
        )
    ]
    separators = [
        SeparatorElement(
            cid=-index,
            page_no=1,
            page_size=page_size,
            orientation=cast(Literal["horizontal", "vertical"], orientation),
            l=float(left),
            b=float(bottom),
            r=float(right),
            t=float(top),
            coord_origin=CoordOrigin.BOTTOMLEFT,
        )
        for index, (orientation, left, bottom, right, top) in enumerate(
            (row.split() for row in separator_rows.strip().splitlines()), start=1
        )
    ]

    order = ReadingOrderPredictor().predict_reading_order(
        page_elements=elements, page_separators=separators
    )

    position = {element.cid: index for index, element in enumerate(order)}
    body = [
        element
        for element in elements
        if element.label not in (DocItemLabel.PAGE_HEADER, DocItemLabel.PAGE_FOOTER)
    ]
    for rule in separators:
        if rule.orientation != "horizontal":
            continue
        spanned = [element for element in body if element.overlaps_horizontally(rule)]
        above = [element.cid for element in spanned if element.b >= rule.b]
        below = [element.cid for element in spanned if element.t <= rule.b]
        early = [(a, z) for a in above for z in below if position[z] < position[a]]
        assert not early, f"read below the rule at y={rule.b:.1f} too early: {early}"


